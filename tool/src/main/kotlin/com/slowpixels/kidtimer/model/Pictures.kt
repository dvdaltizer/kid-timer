/**
 * How a picture moves: every [cycle] ms it shows its second frame [flips] times, each for [step] ms with [step] ms of
 * the first between, and the first frame the rest of the time. A blink is one short flip in a long cycle; flapping wings
 * are one flip in a cycle of two steps, so they never stop.
 */
data class Motion(val cycle: Long, val step: Long, val flips: Int = 1)

/**
 * Which frame [this] shows [t] ms into moving (0 before that, or at a negative [t]). Each [seed] (a tile's place on the
 * screen) goes a little slower or faster and starts at its own point, spread by the golden ratio, so neighbours never
 * blink together and the whole set looks lively rather than in step.
 */
fun Picture.frameAt(t: Long, seed: Int = 0): Int {
    if (t < 0 || frames.size < 2) return 0
    val m = Pictures.motions[id] ?: return 0
    val pace = 1 + 0.25 * (((seed + 1) * 0.618034) % 1.0)
    val cycle = (m.cycle * pace).toLong()
    val step = (m.step * pace).toLong().coerceAtLeast(1)
    val u = Math.floorMod(t + ((((seed + 1) * 0.754878) % 1.0) * cycle).toLong(), cycle)
    return if (u < (2 * m.flips - 1) * step && (u / step) % 2 == 0L) 1 else 0
}
