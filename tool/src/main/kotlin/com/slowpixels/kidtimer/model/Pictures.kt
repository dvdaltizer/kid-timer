package com.slowpixels.kidtimer.model

/**
 * A character for the end of a timer, drawn as 16 × 16 blocks in an 8-bit style: `#` ink, `.` paper, `:` a checker of the
 * two. It has two [frames]; the kid screen flips between them when the time is up, for a little animation (a blink, a
 * flap, a puff of smoke).
 */
data class Picture(val id: String, val name: String, val frames: List<List<String>>) {
    init {
        require(frames.isNotEmpty() && frames.all { f -> f.size == SIZE && f.all { it.length == SIZE && it.all { c -> c in "#.:" } } }) { id }
    }

    /** The drawn part's bounds over every frame, as (left, top, right, bottom) in blocks, right and bottom exclusive. */
    val bounds: IntArray by lazy {
        val all = frames.flatten()
        val cols = (0 until SIZE).filter { c -> all.any { it[c] != '.' } }
        val lines = (0 until SIZE).filter { r -> frames.any { f -> f[r].any { it != '.' } } }
        intArrayOf(cols.first(), lines.first(), cols.last() + 1, lines.last() + 1)
    }

    companion object { const val SIZE = 16 }
}

